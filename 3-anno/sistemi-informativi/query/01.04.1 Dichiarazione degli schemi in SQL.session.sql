CREATE TABLE STUDENTE(
    MATR CHAR(6) PRIMARY KEY,
    NOME VARCHAR(30) NOT NULL,
    CITTA VARCHAR(20),
    CDIP CHAR(3)
);

CREATE TABLE ESAME (
    MATR CHAR(6),
    CODCORSO CHAR(6),
    DATA DATE NOT NULL,
    VOTO SMALLINT NOT NULL,
    PRIMARY KEY (MATR, CODCORSO),
    FOREIGN KEY (MATR) REFERENCES STUDENTE(MATR)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (CODCORSO) REFERENCES CORSO(CODCORSO)
        ON DELETE NO ACTION
        ON UPDATE NO ACTION
);

CREATE TABLE CORSO(
    CODCORSO CHAR(6),
    TITOLO VARCHAR(30) NOT NULL,
    DOCENTE VARCHAR(20),
    PRIMARY KEY(CODCORSO)
);