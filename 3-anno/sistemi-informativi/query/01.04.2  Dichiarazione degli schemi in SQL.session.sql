CREATE TABLE IMPIEGATO(
    MATR CHAR(6) PRIMARY KEY,
    NOME VARCHAR(30) NOT NULL,
    DATASS DATE NOT NULL,
    SALARIO DECIMAL(10,2),
    MATRMGR CHAR(6) DEFAULT 'XXXXXX',
    FOREIGN KEY (MATRMGR) REFERENCES IMPIEGATO(MATR)
        ON DELETE SET DEFAULT
        ON UPDATE CASCADE
);

CREATE TABLE PROGETTO(
    NUMPROG SMALLINT PRIMARY KEY,
    TITOLO VARCHAR(20) NOT NULL,
    TIPO VARCHAR(10)
);

CREATE TABLE ASSEGNAMENTO(
    MATR CHAR(6),
    NUMPROG SMALLINT,
    PERC DECIMAL(3),
    PRIMARY KEY(MATR, NUMPROG),
    FOREIGN KEY (MATR) REFERENCES IMPIEGATO(MATR)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (NUMPROG) REFERENCES PROGETTO(NUMPROG)
        ON DELETE CASCADE
        ON UPDATE CASCADE
)